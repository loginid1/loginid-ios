import Foundation

/// Represents the response from retrieving (asserting) a passkey public key credential.
///
/// All properties are Base64URL-encoded strings derived from the raw binary data.
struct GetPublicKeyResponse {
    /// The credential identifier.
    public let id: String
    
    /// The raw credential identifier.
    public let rawId: String
    
    /// The client data JSON used in the authentication ceremony.
    public let clientDataJSON: String
    
    /// The authenticator data returned by the authenticator.
    public let authenticatorData: String
    
    /// The signature generated by the authenticator.
    public let signature: String
    
    /// The user handle associated with the credential.
    public let userHandle: String

    /**
     Creates a new `GetPublicKeyResponse` by Base64URL-encoding the provided raw data.
     
     - Parameters:
       - id: The credential identifier.
       - rawId: The raw credential identifier.
       - clientDataJSON: The client data JSON.
       - authenticatorData: The authenticator data.
       - signature: The signature from the authenticator.
       - userHandle: The user handle associated with the credential.
     */
    init(
        id: Data,
        rawId: Data,
        clientDataJSON: Data,
        authenticatorData: Data,
        signature: Data,
        userHandle: Data
    ) {
        self.id = id.base64URLEncodedString()
        self.rawId = rawId.base64URLEncodedString()
        self.clientDataJSON = clientDataJSON.base64URLEncodedString()
        self.authenticatorData = authenticatorData.base64URLEncodedString()
        self.signature = signature.base64URLEncodedString()
        self.userHandle = userHandle.base64URLEncodedString()
    }
}
