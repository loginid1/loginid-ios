/// Options used when performing a user action during the checkout-specific MFA authentication flow.
///
/// This is typically used after `beginFlow` has initiated the process,
/// and the user is completing an authentication step.
public struct PerformActionOptions {
    /// The payload required for completing the authentication action.
    ///
    /// This typically contains user input or challenge-response data.
    public let payload: String?
    
    /// An updated transaction payload generated by the merchant to represent the purchase
    /// or operation being confirmed.
    ///
    /// This updates the initial `txPayload` used in the `beginFlow` method.
    public let txPayload: String?
    
    /// Enables passkey support in autofill suggestions (keyboard autofill).
    public let autoFill: Bool?
    
    /// A human-palatable name for the user account, intended only for display on your passkeys.
    public let displayName: String?
    
    /// Creates a new `PerformActionOptions` instance.
    /// - Parameters:
    ///   - payload: Optional payload for completing the authentication factor.
    ///   - txPayload: Optional updated transaction payload.
    ///   - autoFill: Optional flag to enable passkey browser autofill suggestions.
    ///   - displayName: Optional display name for the user account, used in passkeys.
    public init(
        payload: String? = nil,
        txPayload: String? = nil,
        autoFill: Bool? = nil,
        displayName: String? = nil
    ) {
        self.payload = payload
        self.txPayload = txPayload
        self.autoFill = autoFill
        self.displayName = displayName
    }
}
